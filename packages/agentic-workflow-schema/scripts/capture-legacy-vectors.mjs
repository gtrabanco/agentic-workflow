#!/usr/bin/env node
/**
 * P19 / F100 — capture the 3.3.0 behaviour of the pre-feature-26 canonical exports.
 *
 * AC8 pins "all prior machine contracts and pre-feature-26 export meanings remain
 * unchanged", so the bytes the released package produces for a document that
 * carries a leaf outside the JSON data model are part of the contract, not an
 * implementation detail. This script runs the MERGE-BASE build of the package over
 * the shared corpus (`test/fixtures/canonical-legacy-corpus.mjs`) and emits the
 * golden-vector fixture that `test/canonical-legacy-compat.test.mjs` asserts.
 *
 * It never reads the working tree's `src/`, so a vector cannot be back-filled from
 * the code under test — and it fails closed if the two builds disagree about any
 * input the corpus feeds them.
 *
 * Recipe (run from `packages/agentic-workflow-schema`):
 *
 *   MB=$(git merge-base main HEAD)                      # the 3.3.0 source
 *   mkdir -p /tmp/legacy-canonical/src
 *   git show $MB:packages/agentic-workflow-schema/src/index.ts > /tmp/legacy-canonical/src/index.ts
 *   cp tsconfig.json /tmp/legacy-canonical/tsconfig.json
 *   (cd /tmp/legacy-canonical && npx tsc -p tsconfig.json)              # -> out/index.js
 *   node scripts/capture-legacy-vectors.mjs /tmp/legacy-canonical/out/index.js \
 *     > test/fixtures/canonical-legacy-vectors.mjs
 */
import { createRequire } from "node:module";
import { resolve } from "node:path";
import assert from "node:assert/strict";
import {
  CANDIDATE_SNAPSHOT_CONTRACT_ID,
  REVIEW_RECEIPT_CONTRACT_ID,
} from "../dist/index.js";
import { legacyCollisionPair, legacyCompatCases } from "../test/fixtures/canonical-legacy-corpus.mjs";

const require = createRequire(import.meta.url);
const legacyPath = process.argv[2];
if (!legacyPath) {
  console.error("usage: node scripts/capture-legacy-vectors.mjs <compiled merge-base index.js>");
  process.exit(2);
}
const legacy = require(resolve(legacyPath));

// Same inputs on both sides, or the capture proves nothing.
assert.equal(legacy.CANDIDATE_SNAPSHOT_CONTRACT_ID, CANDIDATE_SNAPSHOT_CONTRACT_ID);
assert.equal(legacy.REVIEW_RECEIPT_CONTRACT_ID, REVIEW_RECEIPT_CONTRACT_ID);

const SURFACES = {
  candidateSnapshot: {
    canonical: (value) => legacy.canonicalizeCandidateSnapshot(value),
    digest: (value) => legacy.digestCandidateSnapshot(value),
  },
  reviewReceipt: {
    canonical: (value) => legacy.canonicalizeReviewReceipt(value),
    digest: (value) => legacy.digestReviewReceipt(value),
  },
  // `computeAcceptanceFingerprint` exposes a digest only — no canonical export.
  acceptanceFingerprint: {
    canonical: null,
    digest: (value) => legacy.computeAcceptanceFingerprint(value),
  },
};

function isCanonicalJson(text) {
  try {
    JSON.parse(text);
    return true;
  } catch {
    return false;
  }
}

/**
 * The digest is the byte-identity proof; the canonical string is recorded only
 * where 3.3.0 emitted something that is NOT parseable JSON, because those are the
 * vectors a reader has to see to believe (the `undefined` text and the collapsed
 * empty array that feature 26's guard exists to refuse).
 */
async function capture(surface, value) {
  const { canonical, digest } = SURFACES[surface];
  const vector = { digest: await digest(value) };
  if (canonical) {
    const text = canonical(value);
    if (!isCanonicalJson(text)) vector.canonical = text;
  }
  return vector;
}

const vectors = [];
for (const { name, surface, value } of legacyCompatCases()) {
  try {
    vectors.push({ name, surface, ...(await capture(surface, value)) });
  } catch (failure) {
    // 3.3.0 answered an unsupported leaf with the engine's own error, never a
    // `canonical JSON: unsupported leaf` refusal. The name+message pair is what
    // the compatibility suite holds the candidate to.
    vectors.push({ name, surface, threw: `${failure.name}: ${failure.message}` });
  }
}

const collision = legacyCollisionPair();
const collisionDigests = {
  empty: await SURFACES.reviewReceipt.digest(collision.empty),
  unrepresentable: await SURFACES.reviewReceipt.digest(collision.unrepresentable),
};

const banner = [
  "// GENERATED by scripts/capture-legacy-vectors.mjs — do not hand-edit.",
  "//",
  "// Golden 3.3.0 outputs of the pre-feature-26 canonical exports over the",
  "// unsupported-leaf corpus of canonical-legacy-corpus.mjs (P19 / F100). Each",
  "// vector is the canonical string and digest the RELEASED package produced for",
  "// that document, captured by running the merge-base build itself — see the",
  "// script header for the recipe. Re-run the capture against a different build",
  "// and every vector moves: that is the point. A `canonical` string appears only",
  "// where 3.3.0 emitted unparseable JSON — the byte-identity proof itself is the",
  "// digest, which is the SHA-256 of exactly those bytes.",
  "//",
  "// A leaf is unsupported when it sits outside the JSON data model: undefined, a",
  "// function, a symbol, a bigint, or a non-finite number. 3.3.0 handed those to",
  "// JSON.stringify, which answers the JS value undefined for a function, symbol or",
  "// undefined leaf — the enclosing fragment then interpolates the TEXT undefined (",
  "// an object field) or an EMPTY element (an array, because Array.prototype.join",
  "// renders undefined as nothing) — and throws its own opaque TypeError for a",
  "// bigint. Non-finite numbers serialize as null.",
  "//",
  "// Feature 26's named `unsupported leaf` guard therefore scopes to the",
  "// verification canonicalizers: the legacy exports keep the bytes pinned below,",
  '// which is what AC8 ("pre-feature-26 export meanings remain unchanged") demands.',
  "// The one honest cost is LEGACY_CANONICAL_COLLISION below — 3.3.0 bound two",
  "// different receipts to one digest, and restoring its bytes restores that",
  "// collision on the legacy path only. It is recorded, not hidden.",
];

process.stdout.write(
  banner.join("\n") +
    "\n\nexport const LEGACY_CANONICAL_VECTORS = " +
    JSON.stringify(vectors, null, 2) +
    ";\n\n/** 3.3.0 digests of the two receipts that collide; equal means the collision held. */\n" +
    "export const LEGACY_CANONICAL_COLLISION = " +
    JSON.stringify(collisionDigests, null, 2) +
    ";\n",
);
