/**
 * Operator supervisor template (issue #284).
 *
 * The supervisor is deliberately NOT a runtime component: the package ships a
 * renderer, `advance --print-supervisor` prints the script, and the operator
 * installs it under systemd-run, cron, launchd or any daemon they already run —
 * ask-first, exactly like the provisioning paths of #219. Nothing here writes a
 * file, spawns a process or adds a dependency.
 *
 * The script's whole contract:
 *   - run `pi -p '<advance args>'` in the operator's cwd;
 *   - if the attempt appended a terminal `run/stop` row, stop (a clean stop, a
 *     one-stage hand-off and a human-decision stop are all terminal);
 *   - otherwise the process died — append `supervisor/restart` and re-invoke,
 *     bounded by the restart cap, which records `supervisor/exhausted`;
 *   - a terminal human-decision stop exits 3 so the operator's service manager
 *     reports it instead of hiding it.
 *
 * The restart is a hint: the re-invoked run reconciles from ground truth
 * (`advance --resume`), and git/docs win over anything this script believes.
 */

import { DEFAULT_CONDUCTOR_CONFIG } from "./types.js";

/** The template's identity, printed in the script so an installed copy is traceable. */
export const SUPERVISOR_TEMPLATE = "advance-supervisor@1";

/** Stop codes that mean "a human decides next" — the script exits 3 on them. */
export const SUPERVISOR_HUMAN_STOP_CODES: readonly string[] = [
  "stop-crash-ambiguous",
  "stop-needs-input",
  "stop-blocked",
];

export interface SupervisorSpec {
  /** Project root the conductor runs in. */
  cwd: string;
  /** The pi executable to re-invoke (default `pi`). */
  piBin?: string;
  /** Arguments handed to `pi -p` (default `--resume --continue`). */
  advanceArgs?: string;
  /** Run log path, relative to `cwd` (default: the conductor's own default). */
  runLogPath?: string;
  /** Attempts before the supervisor gives up (default 5). */
  restartCap?: number;
  /** Seconds between attempts (default 15; tests pass 0). */
  backoffSeconds?: number;
}

/** POSIX single-quote a value so the rendered script is injection-safe. */
function sq(value: string): string {
  return `'${value.replace(/'/gu, "'\\''")}'`;
}

/**
 * Render the operator-side supervisor script. Pure: same spec, same bytes.
 */
export function renderSupervisorScript(spec: SupervisorSpec): string {
  const cwd = spec.cwd;
  const piBin = spec.piBin ?? "pi";
  const advanceArgs = spec.advanceArgs ?? "--resume --continue";
  const runLogPath = spec.runLogPath ?? DEFAULT_CONDUCTOR_CONFIG.runLogPath ?? ".agentic-workflow/advance-run.log";
  const restartCap = Math.max(1, Math.trunc(spec.restartCap ?? 5));
  const backoffSeconds = Math.max(0, Math.trunc(spec.backoffSeconds ?? 15));

  return `#!/bin/sh
# ${SUPERVISOR_TEMPLATE} — generated by \`advance --print-supervisor\`; install ask-first.
# A hint, never an authority: the re-invoked run reconciles from ground truth
# (git + the docs) and wins over anything this script believes.
# A run that appends no "run/stop" row died; restart it, bounded by CAP.
set -u
cd ${sq(cwd)} || exit 1
LOG=${sq(runLogPath)}
CAP=${restartCap}
BACKOFF=${backoffSeconds}
mkdir -p "$(dirname "$LOG")"
attempt=0
while :; do
  before=$(wc -l < "$LOG" 2>/dev/null || echo 0)
  ${sq(piBin)} -p ${sq(advanceArgs)}
  status=$?
  after=$(wc -l < "$LOG" 2>/dev/null || echo 0)
  if [ "$after" -gt "$before" ] && tail -n "+$((before + 1))" "$LOG" | grep -q '— run/stop —'; then
    if tail -n "+$((before + 1))" "$LOG" | grep -Eq '— run/stop — (${SUPERVISOR_HUMAN_STOP_CODES.join("|")}) —'; then
      exit 3
    fi
    exit 0
  fi
  attempt=$((attempt + 1))
  if [ "$attempt" -ge "$CAP" ]; then
    printf '%s — supervisor/exhausted — restart cap %s reached after exit %s — %s/%s\\n' "$(date '+%Y-%m-%d %H:%M')" "$CAP" "$status" "$attempt" "$CAP" >> "$LOG"
    exit 1
  fi
  printf '%s — supervisor/restart — previous exit %s — %s/%s\\n' "$(date '+%Y-%m-%d %H:%M')" "$status" "$attempt" "$CAP" >> "$LOG"
  sleep "$BACKOFF"
done
`;
}
