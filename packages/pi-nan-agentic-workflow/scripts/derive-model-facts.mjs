// derive-model-facts.mjs — generates the preset's phase-batching capability
// record from the provider's exported model-facts catalog (issue #695).
//
// What this replaces: `src/phase-batching.ts` used to carry `RECORDED_FACTS`, a
// hand transcription of four facts per model out of the recorded catalog. NaN
// re-cuts that catalog every one to three weeks, and a change touching a routed
// model forced a manual edit plus a patch release across the version train. The
// provider now exports the same facts as typed data with per-cell provenance
// (gtrabanco/pi-nan-provider#47), so this generator is the only writer of
// `src/model-capabilities.generated.ts` and the hand map is gone (IR6).
//
// Two halves, and the split is deliberate:
//
//   the pure core   `deriveModelCapabilities`, `renderArtifact`, the mapping
//                   matrix and the materiality rule — no filesystem, no
//                   provider import, so its obligations run on fixtures under
//                   either runtime.
//   the CLI shell   reads the installed provider's facts, the preset's routed
//                   fleet, the recorded artifact and the credit tariff, then
//                   writes or checks. It needs **bun**: the provider publishes
//                   TypeScript sources and node refuses type stripping for a
//                   file under `node_modules` (`ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING`),
//                   so there is no node fallback for this half — a boundary
//                   this file states instead of discovering.
//
// Materiality is the release-cadence rule (S8): a provider release that does not
// move a recorded cell rewrites nothing and keeps the pin, so an immaterial
// catalog change lights no package. The pin therefore names the release that
// first asserted the recorded facts, never the release that happened to be
// installed the last time someone ran this.
//
// Usage
//   bun scripts/derive-model-facts.mjs --write    # rewrite the artifact
//   bun scripts/derive-model-facts.mjs --check    # verify the committed one
//   bun scripts/derive-model-facts.mjs            # print the fresh artifact
//
// Exit: 0 identical / immaterial / printed · 1 material (stale artifact, or a
// routed model the provider does not export) · 2 usage error · 3 the provider
// module could not be loaded (a skip that names why — never a pass).

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

import { parseJsoncText } from "./jsonc.mjs";

const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** The generated artifact, relative to the package root. It lives under `src/`
 *  because `dist/` is what ships: a snapshot under `catalog/` would be absent
 *  from the published package and the runtime reads this record. */
export const ARTIFACT_PATH = "src/model-capabilities.generated.ts";

/** The recorded cells, in the order the artifact writes them. */
export const RECORD_CELL_KEYS = Object.freeze(["context_window", "tool_harness", "cache_posture"]);

/** Where the marketplace facts come from, and the credit tariff the cache
 *  comparison reads — recorded in the artifact's provenance block. */
export const PROVIDER_PROVENANCE = Object.freeze({
  package: "@gtrabanco/pi-nan-provider",
  repository: "https://github.com/gtrabanco/pi-nan-provider",
  source: 'https://models.dev/api.json (provider "nan"), exported as NAN_MODEL_FACTS with per-cell provenance',
  author: "Helmcode S.L. (NaN) — catalog generated by @gtrabanco/pi-nan-provider",
  license: "MIT",
  credit_tariff: "catalog/nan-catalog-2026-11.jsonc",
});

/** The provider's `toolCalling` union mapped onto the published harness ladder. */
const TOOL_HARNESS_BY_PROTOCOL = Object.freeze({
  "openai-tools": "native",
  xml: "xml",
  unmeasured: "unmeasured",
});

/**
 * The harness a provider protocol denotes.
 *
 * @param {string} toolCalling
 * @returns {"native" | "xml" | "unmeasured"}
 */
export function toolHarnessOf(toolCalling) {
  const harness = Object.hasOwn(TOOL_HARNESS_BY_PROTOCOL, toolCalling)
    ? TOOL_HARNESS_BY_PROTOCOL[toolCalling]
    : undefined;
  if (harness === undefined) {
    throw new TypeError(
      `derive-model-facts: unsupported toolCalling "${String(toolCalling)}" — the provider publishes ${Object.keys(TOOL_HARNESS_BY_PROTOCOL).join(" | ")}`,
    );
  }
  return harness;
}

/**
 * The posture one model states, from the two halves of the question: the
 * provider says whether the cache engages (`cacheMode`), this repository's
 * credit tariff says whether a cached read is cheaper (`rates`). The provider's
 * own `cost` pair is pinned to zero by the credit-pool decision, so it cannot
 * answer the second half.
 *
 * `unmeasured` is always a value, never `flat`: a model that states nothing has
 * stated nothing, and the policy fails closed on it.
 *
 * @param {string} cacheMode
 * @param {{ input: number, cached: number } | undefined} rates
 * @returns {"discounted" | "flat" | "unmeasured"}
 */
export function cachePostureOf(cacheMode, rates) {
  switch (cacheMode) {
    case "unmeasured":
      return "unmeasured";
    case "opt-in":
      // The executor path sends no cache key, so an opt-in cache never engages:
      // a prefix re-read bills at the input rate.
      return "flat";
    case "unsupported":
      return "flat";
    case "automatic": {
      const input = rates?.input;
      const cached = rates?.cached;
      if (typeof input !== "number" || typeof cached !== "number") return "unmeasured";
      return cached < input ? "discounted" : "flat";
    }
    default:
      throw new TypeError(
        `derive-model-facts: unsupported cacheMode "${String(cacheMode)}" — expected automatic | opt-in | unsupported | unmeasured`,
      );
  }
}

/** The three recorded cells plus their inherited source ids, for one model. */
function cellOf(row, rates) {
  return {
    context_window: row.contextWindow,
    tool_harness: toolHarnessOf(row.toolCalling),
    cache_posture: cachePostureOf(row.cacheMode, rates),
    provenance: {
      context_window: row.provenance.contextWindow,
      tool_harness: row.provenance.toolCalling,
      cache_posture: row.provenance.cacheMode,
    },
  };
}

/** Every recorded value, flattened to `slug.cell` so two derivations compare
 *  and report as one list. */
function flatCells(cells) {
  const flat = {};
  for (const [slug, cell] of Object.entries(cells)) {
    for (const key of RECORD_CELL_KEYS) flat[`${slug}.${key}`] = cell[key];
    for (const key of RECORD_CELL_KEYS) flat[`${slug}.provenance.${key}`] = cell.provenance[key];
  }
  return flat;
}

/** The recorded cells that moved, each as `slug.cell: old → new`. */
function diffCells(recorded, fresh) {
  const before = flatCells(recorded ?? {});
  const after = flatCells(fresh);
  const changes = [];
  for (const key of new Set([...Object.keys(before), ...Object.keys(after)])) {
    if (before[key] === after[key]) continue;
    const from = key in before ? String(before[key]) : "(absent)";
    const to = key in after ? String(after[key]) : "(dropped)";
    changes.push(`${key}: ${from} → ${to}`);
  }
  return changes.sort();
}

/**
 * Derive the record for the routed fleet and decide what it means for the
 * release train.
 *
 * @param {object} input
 * @param {Record<string, { contextWindow: number, toolCalling: string, cacheMode: string,
 *   provenance: { contextWindow: string, toolCalling: string, cacheMode: string } }>} input.facts
 *   the provider's exported facts, keyed by model id (extra facts are ignored —
 *   only the three cells this policy reads are consumed)
 * @param {readonly string[]} input.routedModels the preset's routed fleet, in order
 * @param {Record<string, { input: number, cached: number }>} [input.creditRates]
 *   the credit pair per model, from this repository's tariff snapshot
 * @param {Record<string, object>} [input.recorded] the artifact's current cells
 * @param {string} [input.recordedPin] the provider version the artifact names
 * @param {string} input.pin the installed provider version
 * @returns {{ cells: Record<string, object>, pin: string | null,
 *   verdict: { status: "identical" | "immaterial" | "material" | "unexported", changes: string[], unexported: string[] } }}
 *   `status` is the release-train answer: `identical` (nothing to write),
 *   `immaterial` (a newer pin, byte-identical cells — nothing to write, and the
 *   recorded pin stays), `material` (a cell moved or this is the first cut) and
 *   `unexported` (a routed model the provider does not publish — a hole).
 */
export function deriveModelCapabilities({ facts, routedModels, creditRates = {}, recorded, recordedPin, pin }) {
  const unexported = [...routedModels].filter((slug) => !Object.hasOwn(facts, slug)).sort();
  if (unexported.length > 0) {
    return { cells: {}, pin: recordedPin ?? null, verdict: { status: "unexported", changes: [], unexported } };
  }

  const cells = {};
  for (const slug of routedModels) cells[slug] = cellOf(facts[slug], creditRates[slug]);

  const changes = diffCells(recorded, cells);
  const status = changes.length > 0 ? "material" : recordedPin === pin ? "identical" : "immaterial";
  // `material` records the installed release; an immaterial release keeps the
  // one that first asserted these facts, so the file does not churn.
  const recordedPinFor = status === "material" ? pin : recordedPin;

  return { cells, pin: recordedPinFor, verdict: { status, changes, unexported: [] } };
}

/** The provenance block the artifact opens with — the vendored-data rule applied
 *  to generated data: source, author, the exact version copied, and the license. */
function provenanceHeader(pin, modelCount) {
  return [
    "// GENERATED FILE — do not edit. `bun run derive:model-facts` writes it;",
    "// `bun run check:model-facts` verifies the committed copy against the pin.",
    "//",
    "// PROVENANCE",
    "//   What:        the phase-batching capability record's three data cells, one row per routed model",
    `//   Source:      ${PROVIDER_PROVENANCE.source}`,
    `//   Author:      ${PROVIDER_PROVENANCE.author}`,
    `//   Version:     ${PROVIDER_PROVENANCE.package}@${pin} — the release that first asserted these facts`,
    `//   License:     ${PROVIDER_PROVENANCE.license} (${PROVIDER_PROVENANCE.repository})`,
    `//   Tariff:      ${PROVIDER_PROVENANCE.credit_tariff} — the credit pair the cache_posture comparison reads`,
    "//   Cells:       context_window ← contextWindow · tool_harness ← toolCalling ·",
    "//                cache_posture ← cacheMode × the credit pair (automatic + a cheaper cached",
    "//                rate is discounted; opt-in/unsupported bill the input rate; unmeasured states",
    "//                nothing) — each cell carrying the provider's own source id",
    `//   Fleet:       ${modelCount} routed models, one row each; a provider model this preset does`,
    "//                not route is not recorded, which is what keeps an immaterial release silent",
    "//",
    "// `max_phases_per_context` and the thresholds behind it are NOT here: policy",
    "// lives in `src/phase-batching.ts` (NAN_PHASE_THRESHOLDS), never in provider data.",
  ].join("\n");
}

const TYPES = `import type { PhaseBatchingCachePosture, PhaseBatchingToolHarness } from "@gtrabanco/agentic-workflow-schema";

/** One recorded row: the three cells the policy reads, plus the provider's source id per cell. */
export interface GeneratedCapabilityFacts {
  /** The model's context window, in tokens (the provider's \`contextWindow\`). */
  readonly context_window: number;
  /** The executor harness the model documents (the provider's \`toolCalling\`). */
  readonly tool_harness: PhaseBatchingToolHarness;
  /** Whether a cached prefix read is cheaper than a fresh one (\`cacheMode\` × the credit pair). */
  readonly cache_posture: PhaseBatchingCachePosture;
  /** The provider's provenance id for each cell — resolved by the provider's \`NAN_FACT_SOURCES\`. */
  readonly provenance: Readonly<{
    context_window: string;
    tool_harness: string;
    cache_posture: string;
  }>;
}`;

/** The artifact's text: the header, the provenance constants, then one row per
 *  routed model in the preset's order. A pure function of its input — no
 *  timestamp, no map iteration accident — so two runs write identical bytes. */
export function renderArtifact({ pin, cells }) {
  const slugs = Object.keys(cells);
  const rows = slugs.map((slug) => {
    const cell = cells[slug];
    const provenance = RECORD_CELL_KEYS.map((key) => `${key}: ${JSON.stringify(cell.provenance[key])}`).join(", ");
    const values = RECORD_CELL_KEYS.map((key) => `${key}: ${JSON.stringify(cell[key])}`).join(", ");
    return `  ${JSON.stringify(slug)}: Object.freeze({\n    ${values},\n    provenance: Object.freeze({ ${provenance} }),\n  }),`;
  });

  return [
    provenanceHeader(pin, slugs.length),
    "",
    TYPES,
    "",
    "/** The pin and the source classes the rows below inherit. */",
    "export const MODEL_CAPABILITY_PROVENANCE = Object.freeze({",
    `  package: ${JSON.stringify(PROVIDER_PROVENANCE.package)},`,
    `  version: ${JSON.stringify(pin)},`,
    `  repository: ${JSON.stringify(PROVIDER_PROVENANCE.repository)},`,
    `  source: ${JSON.stringify(PROVIDER_PROVENANCE.source)},`,
    `  author: ${JSON.stringify(PROVIDER_PROVENANCE.author)},`,
    `  license: ${JSON.stringify(PROVIDER_PROVENANCE.license)},`,
    `  credit_tariff: ${JSON.stringify(PROVIDER_PROVENANCE.credit_tariff)},`,
    "});",
    "",
    "/** One row per routed model, in the preset's order. */",
    "export const MODEL_CAPABILITY_FACTS: Readonly<Record<string, GeneratedCapabilityFacts>> = Object.freeze({",
    ...rows,
    "});",
    "",
  ].join("\n");
}

// ── The CLI shell ────────────────────────────────────────────────────────

/** Read this package's recorded tariff snapshot: the credit pair per model,
 *  which is the half of the cache-posture question the provider cannot answer. */
function creditRates(root) {
  const snapshot = parseJsoncText(fs.readFileSync(path.join(root, PROVIDER_PROVENANCE.credit_tariff), "utf8"));
  const rates = {};
  for (const model of snapshot.models ?? []) {
    if (model.type !== "chat") continue;
    const pair = model.credits_when_exceeded ?? model.rates;
    const input = pair?.input?.credits_per_1m;
    const cached = pair?.cached?.credits_per_1m;
    if (typeof input === "number" && typeof cached === "number") rates[model.slug] = { input, cached };
  }
  return rates;
}

/** The committed artifact's cells and pin, or `undefined` when it is absent or
 *  unreadable (a corrupt file is a stale artifact, not a reason to stop). */
async function readArtifact(root) {
  const file = path.join(root, ARTIFACT_PATH);
  if (!fs.existsSync(file)) return undefined;
  try {
    const module = await import(pathToFileURL(file).href);
    return { cells: module.MODEL_CAPABILITY_FACTS, pin: module.MODEL_CAPABILITY_PROVENANCE.version };
  } catch {
    return undefined;
  }
}

/** The installed provider's exported facts and version, or a reason it cannot be read. */
async function readProvider(root) {
  try {
    const factsModule = await import(`${PROVIDER_PROVENANCE.package}/src/model-facts.ts`);
    const manifest = JSON.parse(
      fs.readFileSync(path.join(root, "node_modules", PROVIDER_PROVENANCE.package, "package.json"), "utf8"),
    );
    return { facts: factsModule.NAN_MODEL_FACTS, version: manifest.version };
  } catch (error) {
    return { error };
  }
}

async function main(argv) {
  const args = argv.slice(2);
  const mode = args.find((arg) => arg === "--write" || arg === "--check");
  const unknown = args.filter((arg) => arg !== "--write" && arg !== "--check");
  if (unknown.length > 0 || args.length > 1) {
    console.error(`derive-model-facts: unexpected arguments: ${unknown.join(" ") || args.join(" ")}`);
    console.error("Usage: bun scripts/derive-model-facts.mjs [--write | --check]");
    return 2;
  }

  const provider = await readProvider(PACKAGE_ROOT);
  if (provider.error !== undefined) {
    console.error(
      `derive-model-facts: SKIP — cannot read ${PROVIDER_PROVENANCE.package}'s exported facts (${provider.error.message}).`,
    );
    console.error("  This generator runs under bun: the provider publishes TypeScript sources, which node refuses to strip under node_modules.");
    return 3;
  }

  const { NAN_MODELS } = await import(pathToFileURL(path.join(PACKAGE_ROOT, "src/preset.ts")).href);
  const recordedModule = await readArtifact(PACKAGE_ROOT);
  const derived = deriveModelCapabilities({
    facts: provider.facts,
    routedModels: Object.keys(NAN_MODELS),
    creditRates: creditRates(PACKAGE_ROOT),
    recorded: recordedModule?.cells,
    recordedPin: recordedModule?.pin,
    pin: provider.version,
  });

  if (derived.verdict.status === "unexported") {
    console.error(
      `derive-model-facts: FAIL — the provider does not export ${derived.verdict.unexported.join(", ")}, which this preset routes.`,
    );
    console.error("  A routed model with no recorded facts is a hole in the record, not an immaterial change.");
    return 1;
  }

  if (derived.verdict.status === "material" && derived.verdict.changes.length > 0) {
    console.error(`derive-model-facts: ${derived.verdict.changes.length} recorded cell(s) moved at ${PROVIDER_PROVENANCE.package}@${provider.version}:`);
    for (const change of derived.verdict.changes) console.error(`  ${change}`);
  }

  const text = renderArtifact({ pin: derived.pin, cells: derived.cells });

  if (mode === undefined) {
    process.stdout.write(text);
    return 0;
  }

  if (mode === "--write") {
    fs.writeFileSync(path.join(PACKAGE_ROOT, ARTIFACT_PATH), text);
    console.error(`derive-model-facts: wrote ${ARTIFACT_PATH} (${Object.keys(derived.cells).length} rows, ${derived.verdict.status}, pin ${derived.pin}).`);
    return 0;
  }

  const committed = fs.existsSync(path.join(PACKAGE_ROOT, ARTIFACT_PATH))
    ? fs.readFileSync(path.join(PACKAGE_ROOT, ARTIFACT_PATH), "utf8")
    : null;
  if (committed !== text) {
    console.error(`derive-model-facts: STALE — ${ARTIFACT_PATH} is not what the pinned provider facts derive.`);
    console.error("  Run `bun run derive:model-facts` and commit the result.");
    return 1;
  }
  console.error(`derive-model-facts: ${derived.verdict.status} — ${ARTIFACT_PATH} matches ${PROVIDER_PROVENANCE.package}@${provider.version}.`);
  return 0;
}

const invokedDirectly =
  process.argv[1] !== undefined && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  process.exitCode = await main(process.argv);
}
